def detect_template_key(question: str) -> Optional[str]:
    q = question or ""
    for pat, key in _ALIASES:
        if re.search(pat, q, re.I):
            return key
    if re.search(r"صيغ(?:ة|ه)?\s*سريعة|نموذج\s*عقد|قالب|template", q, re.I):
        # قائمة عند الطلب العام
        return "list"
    return None


def format_template(key: str, lang: str = "ar") -> str:
    if key == "list":
        lines = ["الصيغ السريعة المتاحة:"]
        for k, v in TEMPLATES.items():
            lines.append(f"• {v['title_ar']} — اطلبها بالاسم أو بالموضوع")
        lines.append("جميعها مسودات أولية وتحتاج مراجعة قانونية بشرية.")
        return "\n".join(lines)
    item = TEMPLATES.get(key)
    if not item:
        return ""
    title = item.get("title_ar") if lang != "en" else item.get("title_en")
    body = item.get("body_ar") or ""
    return f"{title}\n\n{body}"


def try_legal_template(question: str) -> Optional[str]:
    key = detect_template_key(question)
    if not key:
        return None
    # لا تُرجع قالباً إلا عند طلب صياغة/نموذج صريح أو صيغة سريعة
    q = question or ""
    if key != "list" and not re.search(r"صيغ|نموذج|مسودة|اكتب|صغ|أعد|اعداد|draft|template|صيغة", q, re.I):
        return None
    lang = "en" if re.search(r"[a-z]{4,}", q) and not re.search(r"[\u0600-\u06FF]{3,}", q) else "ar"
    out = format_template(key, lang)
    return out or None


